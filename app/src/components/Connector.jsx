import { getConnectionPointCoords } from '../modules/ShapeGeometry'
import { CANVAS_CONFIG } from '../constants/CANVAS_CONFIG'

/**
 * Generate a quadratic Bézier curve path between two points.
 *
 * Creates smooth, natural-looking connector curves by offsetting the control point
 * vertically by CANVAS_CONFIG.CONNECTION_POINT.curveOffset (50px).
 *
 * @param {number} x1 - Start point x-coordinate
 * @param {number} y1 - Start point y-coordinate
 * @param {number} x2 - End point x-coordinate
 * @param {number} y2 - End point y-coordinate
 * @returns {string} SVG path string in format "M x1 y1 Q cx cy x2 y2"
 *
 * How it works:
 * - Uses quadratic Bézier curve (Q command) for smooth, single-curve paths
 * - Control point cx is the horizontal midpoint between start and end
 * - Control point cy is offset from midpoint by curveOffset to create arc
 * - Offset direction (cy + offset) creates curves that arch downward
 *
 * Empirical tuning: 50px offset was determined to create visually pleasing curves
 * for shapes 200-400px apart. Adjust CANVAS_CONFIG.CONNECTION_POINT.curveOffset
 * if adding support for widely-spaced or close shapes.
 *
 * Example: generateCurvedPath(0, 0, 100, 100) → "M 0 0 Q 50 50 100 100"
 */
function generateCurvedPath(x1, y1, x2, y2) {
  const cx = (x1 + x2) / 2
  const cy = (y1 + y2) / 2
  const offsetY = CANVAS_CONFIG.CONNECTION_POINT.curveOffset
  const controlY = cy + offsetY

  return `M ${x1} ${y1} Q ${cx} ${controlY} ${x2} ${y2}`
}

/**
 * Extract the approximate midpoint from a generated SVG path string.
 *
 * Parses quadratic Bézier path (format: "M x1 y1 Q cx cy x2 y2") to find
 * the midpoint between start and end points for label placement.
 *
 * @param {string} path - SVG path string generated by generateCurvedPath()
 * @returns {Object} Midpoint coordinates { x: number, y: number }
 *
 * Implementation notes:
 * - Splits path by spaces to extract numeric components
 * - Indices: parts[1]=x1, parts[2]=y1, parts[5]=x2, parts[6]=y2
 * - Returns simple arithmetic midpoint, NOT the actual curve midpoint
 * - This is acceptable for label placement (looks good visually)
 *
 * FRAGILE: This function is tightly coupled to generateCurvedPath() output format.
 * If generateCurvedPath() changes the path format, these indices will be wrong.
 * If you modify generateCurvedPath(), update these indices and add tests.
 *
 * Example: getPathMidpoint("M 0 0 Q 50 50 100 100") → { x: 50, y: 50 }
 */
function getPathMidpoint(path) {
  const parts = path.split(' ')
  const x1 = parseFloat(parts[1])
  const y1 = parseFloat(parts[2])
  const x2 = parseFloat(parts[5])
  const y2 = parseFloat(parts[6])

  return {
    x: (x1 + x2) / 2,
    y: (y1 + y2) / 2,
  }
}

export default function Connector({
  connector,
  shapes,
  isSelected,
  onDoubleClick,
  onClick,
}) {
  const sourceShape = shapes.find((s) => s.id === connector.source)
  const targetShape = shapes.find((s) => s.id === connector.target)

  if (!sourceShape || !targetShape) return null

  const sourceCoord = getConnectionPointCoords(sourceShape, connector.sourcePoint)
  const targetCoord = getConnectionPointCoords(targetShape, connector.targetPoint)
  const pathD = generateCurvedPath(sourceCoord.x, sourceCoord.y, targetCoord.x, targetCoord.y)
  const midpoint = getPathMidpoint(pathD)

  return (
    <g
      key={connector.id}
      onMouseDown={(e) => onClick(connector.id, e)}
      onDoubleClick={(e) => onDoubleClick(connector.id, e, connector.label)}
      pointerEvents="bounding-box"
      style={{ cursor: 'pointer' }}
    >
      <path
        d={pathD}
        fill="none"
        stroke="var(--connector-color)"
        strokeWidth="2"
        strokeDasharray={isSelected ? '5,5' : 'none'}
        markerEnd="url(#arrowhead)"
      />

      {/* Selection indicator */}
      {isSelected && (
        <path
          d={pathD}
          fill="none"
          stroke="var(--selection-color)"
          strokeWidth="5"
          opacity="0.5"
          pointerEvents="none"
          markerEnd="url(#arrowhead)"
        />
      )}

      {/* Label background and text */}
      {connector.label && (
        <>
          <rect
            x={midpoint.x - CANVAS_CONFIG.CONNECTOR_LABEL.width / 2}
            y={midpoint.y - CANVAS_CONFIG.CONNECTOR_LABEL.height / 2}
            width={CANVAS_CONFIG.CONNECTOR_LABEL.width}
            height={CANVAS_CONFIG.CONNECTOR_LABEL.height}
            fill="var(--bg-primary)"
            stroke="var(--border-color)"
            strokeWidth="1"
            rx="4"
            pointerEvents="none"
          />
          <text
            x={midpoint.x}
            y={midpoint.y + 4}
            textAnchor="middle"
            dominantBaseline="middle"
            fontSize="12"
            fill="var(--text-primary)"
            fontFamily="'IBM Plex Sans', sans-serif"
            fontWeight="500"
            pointerEvents="none"
            style={{ userSelect: 'none' }}
          >
            {connector.label}
          </text>
        </>
      )}

      {/* Hidden larger target for easier clicking */}
      <path
        d={pathD}
        fill="none"
        stroke="transparent"
        strokeWidth="20"
        pointerEvents="auto"
      />
    </g>
  )
}
